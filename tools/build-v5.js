#!/usr/bin/env node
'use strict';

/*
 * build-v5.js — derive stencils/v5 from stencils/v4 with every Lua generator
 * replaced by the canonical JS text of the lekhjs module that serves its
 * template id (spec 04 §7.2, §8 of Work 01M4X7TCHFB862XGT68GPY071C).
 *
 * v5 is what the TypeScript apps and the lekhjs backend read. v2.2.x, v3 and v4
 * stay frozen with their Lua `scriptfile`s: they are what the C++ apps download.
 *
 *   - Every file of the source folder is copied BYTE FOR BYTE, except a file
 *     holding a generator in script form that is not JS (a `scriptfile`, or a
 *     non-empty `script` without the JS marker) — today only wireframe.json.
 *   - In such a file only the `generator` objects are rewritten, in place in the
 *     text, so every other byte of the file is kept:
 *       {scriptfile, text, embedrefs, interprettext}
 *     becomes
 *       {script: "/*lekh-js:1:<key>*\/...", text, interprettext, embedrefs}
 *     `script` first, then the serializer's order (text, interprettext,
 *     embedrefs), then any other member as it was; `scriptfile` and `type` go.
 *   - The module key comes from the template ID (dispatch is by id, never by
 *     scriptfile) through the frozen tools/wireframe-lua-sources.json. A Lua
 *     generator under an id with no module, or a module with no canonical text,
 *     FAILS the build (exit 1). Native generators (BPMN, table-v1) are left alone.
 *   - _index.json and _text_syntax.json are not copied: they are regenerated by
 *     tools/generate-stencil-index.js --published <to>, and must equal the
 *     source folder's byte for byte (AC-GEN-13), else the build fails.
 *
 * Usage:
 *   node tools/build-v5.js [--from stencils/v4] [--to stencils/v5]
 *                          [--scripts ../lekhjs/src/generators/scripts.generated.json]
 *                          [--core <dir>] [--lua <dir>] [--check] [--quiet]
 *
 *     --check   derive into a temporary folder and compare it with --to file by
 *               file; write nothing and exit 1 if anything differs (missing,
 *               extra or changed files). Run before every lekhboard push until
 *               the TS cutover.
 *     --core, --lua   passed through to generate-stencil-index.js.
 *
 * lekhboard has no build dependency on lekhjs beyond reading the scripts file.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const REPO_ROOT = path.resolve(__dirname, '..');
const LUA_SOURCES_FILE = path.join(__dirname, 'wireframe-lua-sources.json');
const INDEX_TOOL = path.join(__dirname, 'generate-stencil-index.js');
const INDEX_OUTPUTS = ['_index.json', '_text_syntax.json'];
const JS_MARKER = /^\/\*lekh-js:(\d+):([a-z0-9/_-]+)\*\//;
const KEY_ORDER = ['script', 'text', 'interprettext', 'embedrefs'];

function fail(message) {
    process.stderr.write('build-v5: FAILED\n  ' + message.replace(/\n/g, '\n  ') + '\n');
    process.exit(1);
}

function parseArgs(argv) {
    const opts = {
        from: path.join(REPO_ROOT, 'stencils', 'v4'),
        to: path.join(REPO_ROOT, 'stencils', 'v5'),
        scripts: path.resolve(REPO_ROOT, '..', 'lekhjs', 'src', 'generators', 'scripts.generated.json'),
        core: null,
        lua: null,
        check: false,
        quiet: false,
    };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        const value = () => {
            if (i + 1 >= argv.length) { fail(a + ' needs a value'); }
            return argv[++i];
        };
        if (a === '--from') { opts.from = value(); }
        else if (a === '--to') { opts.to = value(); }
        else if (a === '--scripts') { opts.scripts = value(); }
        else if (a === '--core') { opts.core = value(); }
        else if (a === '--lua') { opts.lua = value(); }
        else if (a === '--check') { opts.check = true; }
        else if (a === '--quiet') { opts.quiet = true; }
        else if (a === '-h' || a === '--help') {
            process.stdout.write(fs.readFileSync(__filename, 'utf8').split('\n */')[0].replace(/^\/\*|^ \* ?/gm, '') + '\n');
            process.exit(0);
        } else { fail('unknown argument: ' + a); }
    }
    opts.from = path.resolve(opts.from);
    opts.to = path.resolve(opts.to);
    opts.scripts = path.resolve(opts.scripts);
    if (opts.from === opts.to) { fail('--from and --to are the same folder'); }
    return opts;
}

function readJson(file) {
    let text;
    try { text = fs.readFileSync(file, 'utf8'); } catch (e) { fail('cannot read ' + file + '\n' + e.message); }
    try { return JSON.parse(text); } catch (e) { fail(file + ' is not valid JSON\n' + e.message); }
}

// --- a JSON scanner that keeps source spans ----------------------------------
//
// JSON.parse loses positions, and the rewrite must leave every byte outside the
// generator objects untouched, so the file is scanned once here. Each object
// records its members with the [start, end) span of each value in the text.

function scan(text, file) {
    let i = 0;
    const err = (m) => fail(file + ': ' + m + ' at offset ' + i);
    const ws = () => { while (i < text.length && ' \t\n\r'.indexOf(text[i]) !== -1) { i++; } };
    function str() {
        const start = i;
        i++;
        while (i < text.length && text[i] !== '"') { i += text[i] === '\\' ? 2 : 1; }
        if (i >= text.length) { err('unterminated string'); }
        i++;
        return JSON.parse(text.slice(start, i));
    }
    function value() {
        ws();
        const start = i;
        const c = text[i];
        let node;
        if (c === '{') {
            i++;
            const members = [];
            ws();
            if (text[i] === '}') { i++; }
            else {
                for (;;) {
                    ws();
                    if (text[i] !== '"') { err('expected a key'); }
                    const key = str();
                    ws();
                    if (text[i] !== ':') { err('expected :'); }
                    i++;
                    const v = value();
                    members.push({ key, node: v });
                    ws();
                    if (text[i] === ',') { i++; continue; }
                    if (text[i] === '}') { i++; break; }
                    err('expected , or }');
                }
            }
            node = { kind: 'object', members };
        } else if (c === '[') {
            i++;
            const items = [];
            ws();
            if (text[i] === ']') { i++; }
            else {
                for (;;) {
                    items.push(value());
                    ws();
                    if (text[i] === ',') { i++; continue; }
                    if (text[i] === ']') { i++; break; }
                    err('expected , or ]');
                }
            }
            node = { kind: 'array', items };
        } else if (c === '"') {
            str();
            node = { kind: 'scalar' };
        } else {
            const m = /^(?:-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?|true|false|null)/.exec(text.slice(i, i + 64));
            if (!m) { err('unexpected character'); }
            i += m[0].length;
            node = { kind: 'scalar' };
        }
        node.start = start;
        node.end = i;
        return node;
    }
    const root = value();
    ws();
    if (i !== text.length) { err('trailing text'); }
    return root;
}

// --- classification and conversion (spec 04 §7.2) ----------------------------

/* What a stored generator block is, by the resolver's rules. */
function classify(gen) {
    if (gen.type === 'native') { return 'native'; }
    if (gen.type !== undefined && gen.type !== 'LuaShapeGenerator') { return 'unknown_type'; }
    const script = typeof gen.script === 'string' ? gen.script : '';
    if (JS_MARKER.test(script)) { return 'js'; }
    if (script !== '' || typeof gen.scriptfile === 'string' || gen.type === 'LuaShapeGenerator') { return 'lua'; }
    return 'none';
}

/* The converted member list: [key, rawText | {json}] pairs in the written order. */
function convertedMembers(members, scriptText) {
    const out = [['script', JSON.stringify(scriptText)]];
    const byKey = new Map(members.map((m) => [m.key, m]));
    for (const k of KEY_ORDER) {
        if (k !== 'script' && byKey.has(k)) { out.push([k, byKey.get(k).raw]); }
    }
    for (const m of members) {
        if (m.key === 'scriptfile' || m.key === 'type' || out.some(([k]) => k === m.key)) { continue; }
        out.push([m.key, m.raw]);
    }
    return out;
}

/* The same conversion on parsed JSON, for the semantic self-check. */
function convertedObject(gen, scriptText) {
    const out = { script: scriptText };
    for (const k of KEY_ORDER) {
        if (k !== 'script' && gen[k] !== undefined) { out[k] = gen[k]; }
    }
    for (const k of Object.keys(gen)) {
        if (k === 'scriptfile' || k === 'type' || k in out) { continue; }
        out[k] = gen[k];
    }
    return out;
}

/* The text of the rewritten block, laid out like the block it replaces. */
function blockText(text, node, members) {
    const original = text.slice(node.start, node.end);
    if (original.indexOf('\n') === -1) {
        return '{' + members.map(([k, v]) => JSON.stringify(k) + ': ' + v).join(', ') + '}';
    }
    const firstKey = node.members.length ? node.members[0].keyStart : node.start + 1;
    const lineStart = text.lastIndexOf('\n', firstKey) + 1;
    const indent = text.slice(lineStart, firstKey).replace(/\S.*$/, '');
    const closeLine = text.lastIndexOf('\n', node.end - 1) + 1;
    const closeIndent = text.slice(closeLine, node.end - 1);
    return '{\n' + members.map(([k, v]) => indent + JSON.stringify(k) + ': ' + v).join(',\n') + '\n'
        + (/^\s*$/.test(closeIndent) ? closeIndent : '') + '}';
}

/*
 * Rewrite one file. Returns { text, converted: [{id, key}] }; `text` is the
 * input unchanged when nothing needed converting.
 */
function rewriteFile(text, file, ctx) {
    const root = scan(text, file);
    const edits = [];
    const converted = [];
    const problems = [];

    // Key spans, for the indentation of a rewritten block.
    function keyStarts(node) {
        let at = node.start + 1;
        for (const m of node.members) {
            m.keyStart = text.indexOf('"', at);
            m.raw = text.slice(m.node.start, m.node.end);
            at = m.node.end;
        }
    }

    function visit(node) {
        if (node.kind === 'array') { node.items.forEach(visit); return; }
        if (node.kind !== 'object') { return; }
        keyStarts(node);
        const idMember = node.members.find((m) => m.key === 'id');
        const id = idMember ? JSON.parse(idMember.raw) : '';
        for (const m of node.members) {
            if (m.key === 'generator' && m.node.kind === 'object') {
                keyStarts(m.node);
                const gen = JSON.parse(m.raw);
                const kind = classify(gen);
                if (kind === 'unknown_type') {
                    problems.push(file + ': template ' + JSON.stringify(id) + ' has a generator of unknown type '
                        + JSON.stringify(gen.type) + '.');
                } else if (kind === 'lua') {
                    const key = ctx.keyById.get(id);
                    if (key === undefined) {
                        problems.push(file + ': template ' + JSON.stringify(id) + ' has a Lua generator and no TS module '
                            + '(it is not in ' + path.relative(REPO_ROOT, LUA_SOURCES_FILE) + '). Port it in lekhjs first.');
                        continue;
                    }
                    const script = ctx.scripts[key];
                    if (typeof script !== 'string') {
                        problems.push(file + ': template ' + JSON.stringify(id) + ' maps to module ' + key
                            + ', which has no canonical text in the scripts file.');
                        continue;
                    }
                    if (typeof gen.scriptfile === 'string') {
                        const lua = path.basename(gen.scriptfile).replace(/_min\.lua$/, '');
                        if ('wireframe/' + lua !== key) {
                            problems.push(file + ': template ' + JSON.stringify(id) + ' names ' + gen.scriptfile
                                + ' but its id maps to ' + key + '; the frozen map and the stencil disagree.');
                            continue;
                        }
                    }
                    edits.push({ start: m.node.start, end: m.node.end,
                        text: blockText(text, m.node, convertedMembers(m.node.members, script)) });
                    converted.push({ id, key });
                }
            }
            visit(m.node);
        }
    }
    visit(root);
    if (problems.length) { fail(problems.join('\n')); }
    if (edits.length === 0) { return { text, converted }; }

    edits.sort((a, b) => b.start - a.start);
    let out = text;
    for (const e of edits) { out = out.slice(0, e.start) + e.text + out.slice(e.end); }

    // Self-check: the rewritten text parses to exactly the converted document.
    const expected = (function convert(v, id) {
        if (Array.isArray(v)) { return v.map((x) => convert(x)); }
        if (!v || typeof v !== 'object') { return v; }
        const o = {};
        for (const k of Object.keys(v)) {
            const g = v[k];
            if (k === 'generator' && g && typeof g === 'object' && !Array.isArray(g) && classify(g) === 'lua') {
                o[k] = convertedObject(g, ctx.scripts[ctx.keyById.get(v.id)]);
            } else {
                o[k] = convert(g);
            }
        }
        return o;
    })(JSON.parse(text));
    let actual;
    try { actual = JSON.parse(out); } catch (e) { fail(file + ': the rewritten text is not valid JSON (' + e.message + ')'); }
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
        fail(file + ': the rewritten text does not parse to the converted document; refusing to write it.');
    }
    return { text: out, converted };
}

// --- the build -----------------------------------------------------------------

function loadContext(opts) {
    const scripts = readJson(opts.scripts);
    if (!scripts || typeof scripts !== 'object' || Array.isArray(scripts)) { fail(opts.scripts + ' is not a { key: text } map'); }
    for (const [key, t] of Object.entries(scripts)) {
        const m = typeof t === 'string' ? JS_MARKER.exec(t) : null;
        if (!m || m[1] !== '1' || m[2] !== key) {
            fail(opts.scripts + ': the text of ' + key + ' does not start with /*lekh-js:1:' + key + '*/');
        }
    }
    const sources = readJson(LUA_SOURCES_FILE);
    const keyById = new Map();
    for (const [id, name] of Object.entries(sources)) {
        if (id.startsWith('_')) { continue; }
        if (typeof name !== 'string' || !/^[a-z0-9_]+\.lua$/.test(name)) { fail(LUA_SOURCES_FILE + ': bad source name for ' + id); }
        keyById.set(id, 'wireframe/' + name.replace(/\.lua$/, ''));
    }
    return { scripts, keyById };
}

function build(opts, outDir, log) {
    const ctx = loadContext(opts);
    if (!fs.existsSync(opts.from) || !fs.statSync(opts.from).isDirectory()) { fail('no source folder ' + opts.from); }
    fs.mkdirSync(outDir, { recursive: true });
    const names = fs.readdirSync(opts.from).sort();
    let copied = 0;
    const rewritten = [];
    for (const name of names) {
        const src = path.join(opts.from, name);
        if (!fs.statSync(src).isFile()) { fail(src + ' is not a file; the stencil folders are flat'); }
        if (INDEX_OUTPUTS.includes(name)) { continue; }
        const bytes = fs.readFileSync(src);
        let out = bytes;
        if (name.endsWith('.json')) {
            const text = bytes.toString('utf8');
            if (text.indexOf('"generator"') !== -1) {
                const r = rewriteFile(text, name, ctx);
                if (r.converted.length) {
                    out = Buffer.from(r.text, 'utf8');
                    rewritten.push(name + ' (' + r.converted.length + ' generators)');
                }
            }
        }
        const dst = path.join(outDir, name);
        if (!(fs.existsSync(dst) && fs.readFileSync(dst).equals(out))) { fs.writeFileSync(dst, out); }
        if (out === bytes) { copied++; }
    }
    // Remove what the source folder no longer has (never an index output).
    for (const name of fs.readdirSync(outDir)) {
        if (!names.includes(name)) { fs.rmSync(path.join(outDir, name)); }
    }
    log('copied     ' + copied + ' files byte for byte from ' + path.relative(REPO_ROOT, opts.from));
    log('rewrote    ' + (rewritten.length ? rewritten.join(', ') : 'nothing'));

    const args = [INDEX_TOOL, '--published', outDir, '--quiet'];
    if (opts.core) { args.push('--core', path.resolve(opts.core)); }
    if (opts.lua) { args.push('--lua', path.resolve(opts.lua)); }
    try {
        execFileSync(process.execPath, args, { stdio: ['ignore', 'pipe', 'pipe'] });
    } catch (e) {
        fail('generate-stencil-index.js failed on ' + outDir + '\n' + String(e.stderr || e.message));
    }
    for (const f of INDEX_OUTPUTS) {
        const a = fs.readFileSync(path.join(opts.from, f));
        const b = fs.readFileSync(path.join(outDir, f));
        if (!a.equals(b)) {
            fail(f + ' generated for ' + outDir + ' differs from ' + path.join(opts.from, f)
                + '.\nThe index format is unchanged by the conversion (AC-GEN-13); regenerate the source folder\'s index first.');
        }
    }
    log('index      ' + INDEX_OUTPUTS.join(' and ') + ' equal the source folder\'s byte for byte');
}

function compareDirs(a, b) {
    const diffs = [];
    const an = fs.existsSync(a) ? fs.readdirSync(a).sort() : [];
    const bn = fs.existsSync(b) ? fs.readdirSync(b).sort() : [];
    for (const n of an) {
        if (!bn.includes(n)) { diffs.push('missing in ' + b + ': ' + n); }
        else if (!fs.readFileSync(path.join(a, n)).equals(fs.readFileSync(path.join(b, n)))) { diffs.push('differs: ' + n); }
    }
    for (const n of bn) { if (!an.includes(n)) { diffs.push('extra in ' + b + ': ' + n); } }
    return diffs;
}

// Make `to` hold exactly the files of `from`, writing only the files that differ.
function syncDir(from, to) {
    fs.mkdirSync(to, { recursive: true });
    const names = fs.readdirSync(from);
    for (const name of names) {
        const out = fs.readFileSync(path.join(from, name));
        const dst = path.join(to, name);
        if (!(fs.existsSync(dst) && fs.readFileSync(dst).equals(out))) { fs.writeFileSync(dst, out); }
    }
    for (const name of fs.readdirSync(to)) {
        if (!names.includes(name)) { fs.rmSync(path.join(to, name)); }
    }
}

function main() {
    const opts = parseArgs(process.argv.slice(2));
    const log = opts.quiet ? () => {} : (s) => process.stdout.write(s + '\n');
    // Always derive into a temporary folder first: a failed build (fail() exits) leaves --to
    // untouched, never half written (AC-GEN-14). The exit hook also removes the folder then.
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'lekhboard-v5-'));
    process.on('exit', () => fs.rmSync(tmp, { recursive: true, force: true }));
    if (!opts.check) {
        build(opts, tmp, log);
        syncDir(tmp, opts.to);
        log('wrote      ' + path.relative(REPO_ROOT, opts.to));
        return;
    }
    try {
        build(opts, tmp, log);
        const diffs = compareDirs(tmp, opts.to);
        if (diffs.length) {
            process.stderr.write('build-v5: ' + path.relative(REPO_ROOT, opts.to) + ' is not a fresh derivation of '
                + path.relative(REPO_ROOT, opts.from) + ':\n  ' + diffs.slice(0, 20).join('\n  ')
                + (diffs.length > 20 ? '\n  ... and ' + (diffs.length - 20) + ' more' : '')
                + '\nRun node tools/build-v5.js and commit the result.\n');
            process.exit(1);
        }
        log('check      ' + path.relative(REPO_ROOT, opts.to) + ' is current');
    } finally {
        fs.rmSync(tmp, { recursive: true, force: true });
    }
}

main();
