#!/usr/bin/env node
'use strict';

/*
 * build-noto-fonts.js — the Noto script fonts the web PDF export downloads on demand
 * (spec 08 §6.3 of Work 01M4X7TCHFB862XGT68GPY071C; OQ-55: hosted here, beside the stencils).
 *
 * Writes fonts/noto/:
 *   - one static font per script and weight (Regular, Bold), downloaded from the pinned commits
 *     of notofonts/notofonts.github.io (hinted TTF) and notofonts/noto-cjk (SubsetOTF, CFF);
 *     no variable fonts;
 *   - manifest.json: `<script>` and `<script>-bold` → {file, weight, bytes, sha256}. The keys are
 *     the lower-case Unicode script names lekhjs's splitter produces (`arabic`, `devanagari`, …)
 *     and, for Han, `sc`, `tc`, `jp`, `kr` (Hangul uses `kr`);
 *   - the two OFL-1.1 licence files of the sources.
 *
 * lekhjs (`WebScriptFontProvider`) checks each body's SHA-256 against the manifest before use.
 *
 * Usage:
 *   node tools/build-noto-fonts.js            download and write everything
 *   node tools/build-noto-fonts.js --check    verify the files against manifest.json (exit 1 on a difference)
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'fonts', 'noto');
const NOTO = '5c3913063bb189df4edc94b766584dfb4c04a187'; // notofonts/notofonts.github.io, 2026-10-14
const CJK = 'f8d157532fbfaeda587e826d4cd5b21a49186f7c'; // notofonts/noto-cjk, 2024-09-19

const NOTO_RAW = `https://raw.githubusercontent.com/notofonts/notofonts.github.io/${NOTO}`;
const CJK_RAW = `https://raw.githubusercontent.com/notofonts/noto-cjk/${CJK}`;

/** [manifest key, Noto family suffix] for the hinted TTF families. */
const SCRIPTS = [
  ['arabic', 'Arabic'],
  ['hebrew', 'Hebrew'],
  ['devanagari', 'Devanagari'],
  ['bengali', 'Bengali'],
  ['tamil', 'Tamil'],
  ['telugu', 'Telugu'],
  ['gujarati', 'Gujarati'],
  ['gurmukhi', 'Gurmukhi'],
  ['kannada', 'Kannada'],
  ['malayalam', 'Malayalam'],
  ['sinhala', 'Sinhala'],
  ['thai', 'Thai'],
  ['lao', 'Lao'],
  ['khmer', 'Khmer'],
  ['myanmar', 'Myanmar'],
  ['georgian', 'Georgian'],
  ['armenian', 'Armenian'],
  ['ethiopic', 'Ethiopic'],
];
/** [manifest key, noto-cjk region]. */
const HAN = [
  ['sc', 'SC'],
  ['tc', 'TC'],
  ['jp', 'JP'],
  ['kr', 'KR'],
];

function sources() {
  const out = [];
  for (const [key, fam] of SCRIPTS) {
    for (const [suffix, weight] of [['Regular', 400], ['Bold', 700]]) {
      const file = `NotoSans${fam}-${suffix}.ttf`;
      out.push({ key: weight === 700 ? `${key}-bold` : key, file, weight, url: `${NOTO_RAW}/fonts/NotoSans${fam}/hinted/ttf/${file}` });
    }
  }
  for (const [key, region] of HAN) {
    for (const [suffix, weight] of [['Regular', 400], ['Bold', 700]]) {
      const file = `NotoSans${region}-${suffix}.otf`;
      out.push({ key: weight === 700 ? `${key}-bold` : key, file, weight, url: `${CJK_RAW}/Sans/SubsetOTF/${region}/${file}` });
    }
  }
  return out;
}

const LICENCES = [
  { file: 'OFL-notofonts.txt', url: `${NOTO_RAW}/fonts/LICENSE` },
  { file: 'OFL-noto-cjk.txt', url: `${CJK_RAW}/Sans/LICENSE` },
];

const sha256 = (b) => crypto.createHash('sha256').update(b).digest('hex');

async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return Buffer.from(await r.arrayBuffer());
}

/** An sfnt (TrueType 0x00010000 / 'true') or CFF OpenType ('OTTO'). */
function isFont(b) {
  const tag = b.subarray(0, 4).toString('latin1');
  return tag === 'OTTO' || tag === 'true' || b.readUInt32BE(0) === 0x00010000;
}

async function build() {
  fs.mkdirSync(OUT, { recursive: true });
  const fonts = {};
  for (const s of sources()) {
    const body = await get(s.url);
    if (!isFont(body)) throw new Error(`${s.file}: not a font`);
    fs.writeFileSync(path.join(OUT, s.file), body);
    fonts[s.key] = { file: s.file, weight: s.weight, bytes: body.length, sha256: sha256(body) };
    process.stdout.write(`${s.key.padEnd(16)} ${s.file} ${body.length}\n`);
  }
  for (const l of LICENCES) fs.writeFileSync(path.join(OUT, l.file), await get(l.url));
  const manifest = {
    $comment: 'Generated by tools/build-noto-fonts.js; do not edit. Files are relative to this folder.',
    version: 1,
    sources: {
      'notofonts/notofonts.github.io': NOTO,
      'notofonts/noto-cjk': CJK,
    },
    license: 'OFL-1.1',
    fonts,
  };
  fs.writeFileSync(path.join(OUT, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
}

function check() {
  const m = JSON.parse(fs.readFileSync(path.join(OUT, 'manifest.json'), 'utf8'));
  let bad = 0;
  const want = new Set(sources().map((s) => s.key));
  for (const k of want) if (m.fonts[k] === undefined) {
    process.stderr.write(`missing manifest key ${k}\n`);
    bad++;
  }
  for (const [k, e] of Object.entries(m.fonts)) {
    const p = path.join(OUT, e.file);
    if (!fs.existsSync(p)) {
      process.stderr.write(`${k}: ${e.file} missing\n`);
      bad++;
      continue;
    }
    const b = fs.readFileSync(p);
    if (b.length !== e.bytes || sha256(b) !== e.sha256) {
      process.stderr.write(`${k}: ${e.file} differs from the manifest\n`);
      bad++;
    }
  }
  if (bad > 0) process.exit(1);
  process.stdout.write(`${Object.keys(m.fonts).length} fonts match manifest.json\n`);
}

if (process.argv.includes('--check')) check();
else
  build().catch((e) => {
    process.stderr.write(`${e.message}\n`);
    process.exit(1);
  });
